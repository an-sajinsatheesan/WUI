// Writes src/environments/environment.ts from the API_URL env var before a production build.
// Used by `npm run build:vercel`. API_URL is the public URL of the backend, e.g.
//   https://wui-api.vercel.app/api
import { writeFileSync } from 'node:fs';

const apiUrl = (process.env.API_URL || '').trim().replace(/\/+$/, '');
if (!apiUrl) {
  console.error('API_URL is not set. Add it in Vercel > Project > Settings > Environment Variables.');
  process.exit(1);
}
if (!/^https?:\/\//.test(apiUrl)) {
  console.error(`API_URL must start with http(s)://, got "${apiUrl}"`);
  process.exit(1);
}

const content = `// Generated by scripts/set-env.mjs at build time. Do not edit.
export const environment = {
  production: true,
  apiUrl: ${JSON.stringify(apiUrl)},
};
`;
writeFileSync(new URL('../src/environments/environment.ts', import.meta.url), content);
console.log(`environment.ts -> apiUrl = ${apiUrl}`);
